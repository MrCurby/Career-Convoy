#!/usr/bin/env bash
# Writes the notes of a release.
#
#   tools/release_notes.sh > notes.md      (needs gh with GH_TOKEN, and the tags: fetch-depth 0)
#
# - HEAD is the merge of a release pull request (branch release/v<version>, opened by the
#   "Prepare release" workflow): its text, as it was edited there, is the notes.
# - Otherwise (preparing a release): the install hint, then title and text of every pull request
#   merged into main since the last release (tag v*).
#
# Left out: HTML comments (the hints of .github/pull_request_template.md) and the
# "Generated with/by Claude Code" footers with their session link.
set -euo pipefail
cd "$(dirname "$0")/.."
REPO="${GITHUB_REPOSITORY:-MrCurby/SharedCareer}"

clean() {
	perl -0pe 's/<!--.*?-->[ \t]*\n?//gs; s/\n*(?:---\n)?_Generated by \[Claude Code\]\([^)]*\)_\n?/\n/g' |
		{ grep -v -e '^🤖 Generated with \[Claude Code\]' -e '^https://claude\.ai/code/session_' || true; }
}
# Pull requests merged into main with this commit, as "<number> <branch>".
merged_prs() {
	gh api "repos/$REPO/commits/$1/pulls" \
		--jq '.[] | select(.merged_at != null and .base.ref == "main") | "\(.number) \(.head.ref)"'
}

RELEASE_PR=$(merged_prs "$(git rev-parse HEAD)" | awk '$2 ~ /^release\// { print $1; exit }')
if [ -n "$RELEASE_PR" ]; then
	gh pr view "$RELEASE_PR" --repo "$REPO" --json body --jq .body | clean
	exit 0
fi

echo "Install on a server: \`./server.sh update\` (downloads this release automatically)."

LAST=$(git describe --tags --abbrev=0 --match 'v[0-9]*' HEAD 2>/dev/null || true)
RANGE="${LAST:+$LAST..}HEAD"

# Commits straight on main are the merge (or squash) commits of the pull requests.
PRS=$(git log --first-parent --format=%H "$RANGE" | while read -r sha; do
	merged_prs "$sha"
done | awk '$2 !~ /^release\// && !seen[$1]++ { print $1 }')

for pr in $PRS; do
	gh pr view "$pr" --repo "$REPO" --json title,body,url \
		--template '{{"\n## "}}{{.title}} ({{.url}}){{"\n\n"}}{{.body}}{{"\n"}}' | clean
done
