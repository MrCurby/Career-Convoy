-- SharedCareer :: garage, computers and walking in multiplayer
--
-- 1. Duplicate cars when tuning/installing parts/painting
--    The garage rebuilds a car with core_vehicles.replaceVehicle(model, opt, theCar).
--    BeamMP replaces replaceVehicle with its own version, which ignores the given car
--    and rebuilds getPlayerVehicle(0) instead. At the garage computer you are on foot,
--    though -> the player on foot (or another car) becomes the copy, and two cars end up
--    inside each other. Fix: for the duration of that one call, getPlayerVehicle(0) returns
--    exactly the car the garage meant.
--
-- 2. Invisible player on foot
--    The career spawns the unicycle without a mesh (in single player nobody sees you).
--    In multiplayer the visible BeamMP variant is used.
--
-- 3. The computer menu closes by itself
--    The menu closes when you are >1 m away from the door. Position syncing wobbles more
--    than that. For the computer the radius is extended to 25 m.
--    Also, for tuning/parts/painting you are put into the clicked car, because these menus
--    work with the car you are sitting in.
--
-- 4. Using computers from a distance
--    On West Coast USA the mod ships enlarged zones for the four garage computers as a
--    map file (client/levels/.../garage_interactions/items.level.json, generated by
--    tools/zones/make_garage_zones.py from the BeamNG original). The zone reaches
--    14 x 12 m from the computer into the room.
--    Additionally (for other maps/computers), section 4 below enlarges zones while playing
--    to at least client.computerAccessRange meters.
--
-- Career modules are reloaded on every start, so every second we check whether the
-- wrappers still sit on the current table.

local M = {}

local U

local CAREER_UNICYCLE = "vehicles/unicycle/without_mesh.pc"
local MP_UNICYCLE = "vehicles/unicycle/beammp_default.pc"
local COMPUTER_RANGE = 25
local CHECK_EVERY = 1

local sinceCheck = CHECK_EVERY
local rebuilding = false

--== 1. Garage rebuild ==========================================================

local function ownCarId(veh)
	if veh == nil then
		return nil
	end
	local ok, id = pcall(function()
		return veh:getID()
	end)
	if not ok or type(id) ~= "number" then
		return nil
	end
	local mp = rawget(_G, "MPVehicleGE")
	if type(mp) ~= "table" or type(mp.isOwn) ~= "function" then
		return nil
	end
	if not mp.isOwn(id) then
		return nil
	end
	return id
end

-- Inventory ID if the vehicle is a car from our own career garage.
local function inventoryIdOf(veh)
	local inventory = career_modules_inventory
	if type(inventory) ~= "table" or type(inventory.getInventoryIdFromVehicleId) ~= "function" then
		return nil
	end
	local ok, id = pcall(function()
		return inventory.getInventoryIdFromVehicleId(veh:getID())
	end)
	if ok then
		return id
	end
	return nil
end

local function makeReplaceVehicle(original)
	return function(modelName, opt, otherVeh, ...)
		-- We may sit in the chain several times (BeamMP wraps us, we wrap BeamMP).
		-- Only the outermost level does something.
		if rebuilding or not U.isMP() then
			return original(modelName, opt, otherVeh, ...)
		end
		local id = ownCarId(otherVeh)
		if not id then
			if otherVeh ~= nil and inventoryIdOf(otherVeh) ~= nil then
				-- A car BeamMP doesn't know as ours: don't touch it, otherwise a copy appears
				-- that the garage doesn't know.
				U.log("W", "garage", "refused to rebuild a vehicle that is not ours")
				U.toast("warning", "This car is not linked to you on the server and was not changed.", 8)
				return nil
			end
			return original(modelName, opt, otherVeh, ...)
		end
		local previous = rawget(_G, "getPlayerVehicle")
		local real = previous or getPlayerVehicle
		rawset(_G, "getPlayerVehicle", function(player, ...)
			if player == 0 then
				return otherVeh
			end
			return real(player, ...)
		end)
		rebuilding = true
		local results = U.pack(xpcall(original, debug.traceback, modelName, opt, otherVeh, ...))
		rebuilding = false
		rawset(_G, "getPlayerVehicle", previous)
		if not results[1] then
			U.log("E", "garage", "rebuild of vehicle " .. id .. " failed: " .. tostring(results[2]))
			error(results[2], 0)
		end
		return U.unpack(results, 2, results.n)
	end
end

--== 2. Visible player on foot =================================================

local function makeSpawnNewVehicle(original)
	return function(modelName, opt, ...)
		if
			U.isMP()
			and modelName == "unicycle"
			and type(opt) == "table"
			and opt.config == CAREER_UNICYCLE
			and FS:fileExists(MP_UNICYCLE)
		then
			opt = deepcopy(opt)
			opt.config = MP_UNICYCLE
		end
		return original(modelName, opt, ...)
	end
end

--== 3. Computer range ==========================================================

local function withWideTether(fn, ...)
	local tether = career_modules_tether
	if type(tether) ~= "table" then
		return fn(...)
	end
	local door, sphere = tether.startDoorTether, tether.startSphereTether
	local function widen(start)
		if type(start) ~= "function" then
			return start
		end
		return function(target, range, ...)
			if type(range) == "number" and range < COMPUTER_RANGE then
				range = COMPUTER_RANGE
			end
			return start(target, range, ...)
		end
	end
	tether.startDoorTether, tether.startSphereTether = widen(door), widen(sphere)
	local results = U.pack(pcall(fn, ...))
	tether.startDoorTether, tether.startSphereTether = door, sphere
	if not results[1] then
		error(results[2], 0)
	end
	return U.unpack(results, 2, results.n)
end

-- The car for which a button was last pressed at the computer.
local clickedInventoryId = nil

local function makeOpenMenu(original)
	return function(...)
		clickedInventoryId = nil
		if not U.isMP() then
			return original(...)
		end
		return withWideTether(original, ...)
	end
end

local function makeButtonCallback(original)
	return function(buttonId, inventoryId, ...)
		clickedInventoryId = inventoryId
		return original(buttonId, inventoryId, ...)
	end
end

-- Tuning, parts and painting work with the vehicle you are sitting in. At the computer
-- you are on foot, so we put the player into the clicked car.
local function enterMenuVehicle()
	if not U.isMP() then
		return
	end
	local inventory = career_modules_inventory
	local inventoryId = clickedInventoryId
	clickedInventoryId = nil
	if type(inventory) ~= "table" or not inventoryId then
		return
	end
	local vehId = inventory.getVehicleIdFromInventoryId and inventory.getVehicleIdFromInventoryId(inventoryId)
	local veh = vehId and be:getObjectByID(vehId)
	if not veh or veh.JBeam == "unicycle" or be:getPlayerVehicleID(0) == vehId then
		return
	end
	if gameplay_walk and gameplay_walk.isWalking and gameplay_walk.isWalking() then
		gameplay_walk.getInVehicle(veh)
	else
		be:enterVehicle(0, veh)
	end
end

M.onCareerTuningStarted = enterMenuVehicle
M.onPartShoppingStarted = enterMenuVehicle
M.onVehiclePaintingUiOpened = enterMenuVehicle

